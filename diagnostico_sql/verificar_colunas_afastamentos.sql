-- 1) Colunas candidatas em TRABALHADOR e DEPENDENTES
SELECT TRIM(RDB$RELATION_NAME) AS TABELA, TRIM(RDB$FIELD_NAME) AS CAMPO
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME IN ('TRABALHADOR', 'DEPENDENTES')
  AND (RDB$FIELD_NAME CONTAINING 'NOME'
    OR RDB$FIELD_NAME CONTAINING 'CPF'
    OR RDB$FIELD_NAME CONTAINING 'MATRIC'
    OR RDB$FIELD_NAME CONTAINING 'NASC'
    OR RDB$FIELD_NAME CONTAINING 'DIVIS'
    OR RDB$FIELD_NAME CONTAINING 'CARGO')
ORDER BY 1, 2;

-- 2) Qual coluna do TRABALHADOR aponta para DIVISAO e para CARGOS
SELECT TRIM(rc2.RDB$RELATION_NAME) AS REFERENCIA, TRIM(s.RDB$FIELD_NAME) AS CAMPO
FROM RDB$RELATION_CONSTRAINTS rc
JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME = rc.RDB$INDEX_NAME
JOIN RDB$REF_CONSTRAINTS ref ON ref.RDB$CONSTRAINT_NAME = rc.RDB$CONSTRAINT_NAME
JOIN RDB$RELATION_CONSTRAINTS rc2 ON rc2.RDB$CONSTRAINT_NAME = ref.RDB$CONST_NAME_UQ
WHERE rc.RDB$RELATION_NAME = 'TRABALHADOR'
  AND rc.RDB$CONSTRAINT_TYPE = 'FOREIGN KEY'
  AND rc2.RDB$RELATION_NAME IN ('DIVISAO', 'CARGOS')
ORDER BY 1, s.RDB$FIELD_POSITION;
