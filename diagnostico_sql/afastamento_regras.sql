-- A1) Vigentes na data da cópia, por tipo (vínculos ativos)
SELECT m.REDUZIDO, r.NOME, COUNT(DISTINCT m.REGISTRO) AS VINCULOS
FROM MOVTOSEFIP m
JOIN SEFIPREDUZIDO r ON r.EMPRESA = m.EMPRESA AND r.CODIGO = m.REDUZIDO
JOIN TRABALHADOR t ON t.EMPRESA = m.EMPRESA AND t.REGISTRO = m.REGISTRO
WHERE m.EMPRESA = '001' AND t.SITUACAO = 1 AND r.SEFIPENT IS NOT NULL
  AND m.DTINI <= DATE '2026-09-29'
  AND (m.DTFIM IS NULL OR m.DTFIM > DATE '2026-09-29')
GROUP BY m.REDUZIDO, r.NOME
ORDER BY 3 DESC;

-- A5) Status eSocial dos afastamentos desde 2025
SELECT m.REDUZIDO, m.STATUS_ESOCIAL, COUNT(*) AS QTD
FROM MOVTOSEFIP m
JOIN SEFIPREDUZIDO r ON r.EMPRESA = m.EMPRESA AND r.CODIGO = m.REDUZIDO
WHERE m.EMPRESA = '001' AND r.SEFIPENT IS NOT NULL AND m.DTINI >= '2025-01-01'
GROUP BY m.REDUZIDO, m.STATUS_ESOCIAL
ORDER BY 1, 2;

-- A7) Pares de afastamentos sobrepostos no mesmo REGISTRO desde 2025
SELECT COUNT(*) AS PARES_SOBREPOSTOS
FROM MOVTOSEFIP a
JOIN SEFIPREDUZIDO ra ON ra.EMPRESA = a.EMPRESA AND ra.CODIGO = a.REDUZIDO
JOIN MOVTOSEFIP b ON b.EMPRESA = a.EMPRESA AND b.REGISTRO = a.REGISTRO AND b.ITEM > a.ITEM
JOIN SEFIPREDUZIDO rb ON rb.EMPRESA = b.EMPRESA AND rb.CODIGO = b.REDUZIDO
WHERE a.EMPRESA = '001' AND a.DTINI >= '2025-01-01'
  AND ra.SEFIPENT IS NOT NULL AND rb.SEFIPENT IS NOT NULL
  AND b.DTINI < COALESCE(a.DTFIM, DATE '2999-12-31')
  AND a.DTINI < COALESCE(b.DTFIM, DATE '2999-12-31');
