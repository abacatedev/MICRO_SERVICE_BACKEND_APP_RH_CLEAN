-- 1) Colunas das tabelas centrais, na ordem
SELECT TRIM(RDB$RELATION_NAME) AS TABELA, RDB$FIELD_POSITION AS POS, TRIM(RDB$FIELD_NAME) AS CAMPO
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME IN ('MOVTOSEFIP','SEFIPREDUZIDO','CODMOVSEFIP','CAUSAS','CAUSAS_SITUACOES',
                            'CID','CID_MOVTOSEFIP','MEDICOS','CODSEFIP_SITUACOES','PERICIA_AFASTAMENTO')
ORDER BY 1, 2;

-- 2) Chaves primárias e estrangeiras dessas tabelas
SELECT TRIM(rc.RDB$RELATION_NAME) AS TABELA,
       TRIM(rc.RDB$CONSTRAINT_TYPE) AS TIPO,
       TRIM(s.RDB$FIELD_NAME) AS CAMPO,
       TRIM(rc2.RDB$RELATION_NAME) AS REFERENCIA
FROM RDB$RELATION_CONSTRAINTS rc
JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME = rc.RDB$INDEX_NAME
LEFT JOIN RDB$REF_CONSTRAINTS ref ON ref.RDB$CONSTRAINT_NAME = rc.RDB$CONSTRAINT_NAME
LEFT JOIN RDB$RELATION_CONSTRAINTS rc2 ON rc2.RDB$CONSTRAINT_NAME = ref.RDB$CONST_NAME_UQ
WHERE rc.RDB$RELATION_NAME IN ('MOVTOSEFIP','SEFIPREDUZIDO','CODMOVSEFIP','CAUSAS','CAUSAS_SITUACOES',
                               'CID','CID_MOVTOSEFIP','MEDICOS','CODSEFIP_SITUACOES','PERICIA_AFASTAMENTO')
  AND rc.RDB$CONSTRAINT_TYPE IN ('PRIMARY KEY','FOREIGN KEY')
ORDER BY 1, 2, rc.RDB$CONSTRAINT_NAME, s.RDB$FIELD_POSITION;

-- 3) Quem aponta para MOVTOSEFIP
SELECT TRIM(rc.RDB$RELATION_NAME) AS TABELA_FILHA, TRIM(rc.RDB$CONSTRAINT_NAME) AS FK
FROM RDB$RELATION_CONSTRAINTS rc
JOIN RDB$REF_CONSTRAINTS ref ON ref.RDB$CONSTRAINT_NAME = rc.RDB$CONSTRAINT_NAME
JOIN RDB$RELATION_CONSTRAINTS pk ON pk.RDB$CONSTRAINT_NAME = ref.RDB$CONST_NAME_UQ
WHERE pk.RDB$RELATION_NAME = 'MOVTOSEFIP'
ORDER BY 1;

