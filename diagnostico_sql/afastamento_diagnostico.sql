-- 2) Uso de cada tipo na empresa 001 (total e desde 2025)
SELECT m.REDUZIDO, r.NOME, r.SEFIPSAI, r.SEFIPENT,
       COUNT(*) AS TOTAL,
       SUM(IIF(m.DTINI >= '2025-01-01', 1, 0)) AS DESDE_2025
FROM MOVTOSEFIP m
LEFT JOIN SEFIPREDUZIDO r ON r.EMPRESA = m.EMPRESA AND r.CODIGO = m.REDUZIDO
WHERE m.EMPRESA = '001'
GROUP BY m.REDUZIDO, r.NOME, r.SEFIPSAI, r.SEFIPENT
ORDER BY 5 DESC;

-- 3) Completude dos afastamentos temporários desde 2025, por tipo
SELECT m.REDUZIDO,
       COUNT(*) AS TOTAL,
       SUM(IIF(m.CIDMEDICO IS NULL AND m.CIDPERITO IS NULL
               AND NOT EXISTS (SELECT 1 FROM CID_MOVTOSEFIP c WHERE c.ITEM_MOVTOSEFIP = m.ITEM), 1, 0)) AS SEM_CID,
       SUM(IIF(m.MEDICO IS NULL AND m.PERITO IS NULL, 1, 0)) AS SEM_MEDICO,
       SUM(IIF(m.DT_PERICIA IS NULL, 1, 0)) AS SEM_PERICIA,
       SUM(IIF(m.TIPOLEGAL IS NULL OR m.NUMDOCUMENTO IS NULL, 1, 0)) AS SEM_DOCUMENTO,
       SUM(IIF(m.IDPDF IS NULL, 1, 0)) AS SEM_PDF,
       SUM(IIF(m.DTFIM IS NULL, 1, 0)) AS SEM_DTFIM,
       SUM(IIF(m.DTALTA IS NULL, 1, 0)) AS SEM_ALTA,
       SUM(IIF(m.STATUS_ESOCIAL IS NULL, 1, 0)) AS SEM_STATUS_ESOCIAL
FROM MOVTOSEFIP m
JOIN SEFIPREDUZIDO r ON r.EMPRESA = m.EMPRESA AND r.CODIGO = m.REDUZIDO
WHERE m.EMPRESA = '001' AND r.SEFIPENT IS NOT NULL AND m.DTINI >= '2025-01-01'
GROUP BY m.REDUZIDO
ORDER BY 2 DESC;

-- 4) Situação 3 (Afastado) sem afastamento vigente
SELECT COUNT(*) AS AFASTADOS_SEM_MOVTO_VIGENTE
FROM TRABALHADOR t
WHERE t.EMPRESA = '001' AND t.SITUACAO = 3
  AND NOT EXISTS (SELECT 1 FROM MOVTOSEFIP m
                  WHERE m.EMPRESA = t.EMPRESA AND m.REGISTRO = t.REGISTRO
                    AND m.DTINI <= CURRENT_DATE
                    AND (m.DTFIM IS NULL OR m.DTFIM > CURRENT_DATE));

-- 5) Situação 1 (Normal) com afastamento temporário vigente
SELECT COUNT(*) AS NORMAIS_COM_AFAST_VIGENTE
FROM TRABALHADOR t
WHERE t.EMPRESA = '001' AND t.SITUACAO = 1
  AND EXISTS (SELECT 1 FROM MOVTOSEFIP m
              JOIN SEFIPREDUZIDO r ON r.EMPRESA = m.EMPRESA AND r.CODIGO = m.REDUZIDO
              WHERE m.EMPRESA = t.EMPRESA AND m.REGISTRO = t.REGISTRO
                AND r.SEFIPENT IS NOT NULL
                AND m.DTINI <= CURRENT_DATE
                AND (m.DTFIM IS NULL OR m.DTFIM > CURRENT_DATE));

-- 6) Total na situação 3 hoje
SELECT COUNT(*) AS TOTAL_SITUACAO_3 FROM TRABALHADOR WHERE EMPRESA = '001' AND SITUACAO = 3;
