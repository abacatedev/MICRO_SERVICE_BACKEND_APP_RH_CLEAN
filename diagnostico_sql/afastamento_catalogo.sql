-- 1) Tabelas candidatas a afastamento/licença/CID/perícia
SELECT TRIM(RDB$RELATION_NAME) AS TABELA
FROM RDB$RELATIONS
WHERE RDB$SYSTEM_FLAG = 0
  AND (RDB$RELATION_NAME CONTAINING 'AFAST'
    OR RDB$RELATION_NAME CONTAINING 'LICEN'
    OR RDB$RELATION_NAME CONTAINING 'OCORR'
    OR RDB$RELATION_NAME CONTAINING 'CID'
    OR RDB$RELATION_NAME CONTAINING 'PERICIA'
    OR RDB$RELATION_NAME CONTAINING 'MEDIC'
    OR RDB$RELATION_NAME CONTAINING 'CAUSA')
ORDER BY 1;

-- 2) Colunas de SEFIP, CID, CRM, motivo eSocial e período
SELECT TRIM(RDB$RELATION_NAME) AS TABELA, TRIM(RDB$FIELD_NAME) AS CAMPO
FROM RDB$RELATION_FIELDS
WHERE RDB$SYSTEM_FLAG = 0
  AND (RDB$FIELD_NAME CONTAINING 'SEFIP'
    OR RDB$FIELD_NAME CONTAINING 'CID'
    OR RDB$FIELD_NAME CONTAINING 'CRM'
    OR RDB$FIELD_NAME CONTAINING 'MOTAFAST'
    OR RDB$FIELD_NAME CONTAINING 'DTAFAST'
    OR RDB$FIELD_NAME CONTAINING 'RETORNO')
ORDER BY 1, 2;
